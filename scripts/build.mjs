// Bundles src/ into the single Client module DSH loads: dsh-snake/client.js.
// Usage: node scripts/build.mjs [--watch]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const root = fileURLToPath(new URL('..', import.meta.url));
const outfile = `${root}dsh-snake/client.js`;
const { name: id } = JSON.parse(await readFile(`${root}dsh-snake/package.json`, 'utf8'));

/** DSH's module loader passes `require` for the host's module table (React lives there). */
function wrap(code) {
  const body = code.trimEnd().replace(/^/gm, '    ');
  return `// Generated by scripts/build.mjs from src/. Do not edit by hand.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(id)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${body}
    return module.exports;
  },
});
`;
}

const writeBundle = {
  name: 'dsh-module-loader',
  setup(build) {
    build.onEnd(async (result) => {
      if (result.errors.length > 0) return;
      const [output] = result.outputFiles;
      await writeFile(outfile, wrap(output.text));
      console.log(`built ${outfile.slice(root.length)} (${output.contents.length} bytes)`);
    });
  },
};

const options = {
  entryPoints: [`${root}src/index.jsx`],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react'],
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  loader: { '.css': 'text' },
  legalComments: 'none',
  logLevel: 'warning',
  plugins: [writeBundle],
};

if (process.argv.includes('--watch')) {
  const context = await esbuild.context(options);
  await context.watch();
  console.log('watching src/');
} else {
  await esbuild.build(options);
}
